import { useEffect, useRef, useState } from 'react';
import * as THREE from 'three';
import { RoundedBoxGeometry } from 'three/addons/geometries/RoundedBoxGeometry.js';
import { RoomEnvironment } from 'three/addons/environments/RoomEnvironment.js';
import btcSvg from 'cryptocurrency-icons/svg/color/btc.svg?raw';
import ethSvg from 'cryptocurrency-icons/svg/color/eth.svg?raw';
const btcLogo='data:image/svg+xml;charset=utf-8,'+encodeURIComponent(btcSvg.replace('<svg','<svg width="256" height="256"'));
const ethLogo='data:image/svg+xml;charset=utf-8,'+encodeURIComponent(ethSvg.replace('<svg','<svg width="256" height="256"'));

export default function GoldScene({ paused = false }: { paused?: boolean }) {
  const host = useRef<HTMLDivElement>(null);
  const pauseRef = useRef(paused);
  useEffect(() => { pauseRef.current = paused; }, [paused]);
  const [failed, setFailed] = useState(false);
  useEffect(() => {
    const el = host.current;
    if (!el) return;
    let renderer: THREE.WebGLRenderer;
    try { renderer = new THREE.WebGLRenderer({ alpha: true, antialias: true, powerPreference: 'low-power' }); }
    catch { setFailed(true); return; }
    renderer.setPixelRatio(Math.min(window.devicePixelRatio, 1.65));
    renderer.outputColorSpace = THREE.SRGBColorSpace;
    renderer.toneMapping = THREE.ACESFilmicToneMapping;
    renderer.toneMappingExposure = 1.12;
    el.appendChild(renderer.domElement);
    const scene = new THREE.Scene();
    const camera = new THREE.PerspectiveCamera(34, 1, 0.1, 50);
    camera.position.set(0, 0, 10.8);
    const pmrem = new THREE.PMREMGenerator(renderer);
    const room = new RoomEnvironment();
    const environment = pmrem.fromScene(room, 0.04);
    scene.environment = environment.texture;
    const main = new THREE.Group();
    scene.add(main);
    const gold = new THREE.MeshStandardMaterial({ color: '#e9b34e', metalness: 0.96, roughness: 0.22 });
    const brightGold = new THREE.MeshStandardMaterial({ color: '#f3ce72', metalness: 0.87, roughness: 0.28 });
    const bar = new THREE.Group();
    const body = new THREE.Mesh(new RoundedBoxGeometry(2.32, 3.55, 0.54, 5, 0.17), gold);
    bar.add(body);
    const canvas = document.createElement('canvas'); canvas.width = 640; canvas.height = 960;
    const ctx = canvas.getContext('2d')!;
    ctx.clearRect(0, 0, 640, 960);
    ctx.strokeStyle = '#80551b'; ctx.lineWidth = 3;
    ctx.beginPath(); ctx.roundRect(40, 35, 560, 890, 40); ctx.stroke();
    ctx.textAlign = 'center'; ctx.fillStyle = '#694215';
    ctx.font = '500 25px Arial'; ctx.fillText('G O L D S W A P', 320, 155);
    ctx.strokeStyle = '#75501d'; ctx.lineWidth = 7;
    ctx.beginPath(); ctx.moveTo(250,260); ctx.lineTo(390,260); ctx.lineTo(440,360); ctx.lineTo(200,360); ctx.closePath(); ctx.stroke();
    ctx.beginPath(); ctx.moveTo(270,260); ctx.lineTo(295,360); ctx.moveTo(370,260); ctx.lineTo(345,360); ctx.stroke();
    ctx.font = '500 83px Georgia'; ctx.fillText('Au',320,500);
    ctx.font = '500 26px Arial'; ctx.fillText('F I N E   G O L D',320,580);
    ctx.font = '500 53px Arial'; ctx.fillText('999.9',320,663);
    ctx.font = '400 21px Arial'; ctx.fillText('A NEW STANDARD',320,810);
    ctx.fillText('FOR GOLD',320,845);
    const texture = new THREE.CanvasTexture(canvas);
    texture.colorSpace = THREE.SRGBColorSpace;
    const labelMat = new THREE.MeshStandardMaterial({ map: texture, transparent: true, metalness: .32, roughness: .65, depthWrite: false });
    const label = new THREE.Mesh(new THREE.PlaneGeometry(2.22,3.35),labelMat); label.position.z = .279; bar.add(label);
    bar.rotation.set(-.17, -.46, -.23); bar.position.set(.04,.12,0); main.add(bar);
    const coinGeometry = new THREE.CylinderGeometry(.68,.68,.15,64);
    const coin1 = new THREE.Group();
    const disc = new THREE.Mesh(coinGeometry, brightGold); disc.rotation.x = Math.PI / 2; coin1.add(disc);
    const rim = new THREE.Mesh(new THREE.TorusGeometry(.60,.018,8,64),gold); rim.position.z=.085; coin1.add(rim);
    const ctex = new THREE.TextureLoader().load(btcLogo); ctex.colorSpace=THREE.SRGBColorSpace;
    const cmaterial = new THREE.MeshStandardMaterial({map:ctex,transparent:true,roughness:.6,metalness:.5,depthWrite:false});
    const clabel = new THREE.Mesh(new THREE.PlaneGeometry(1.14,1.14),cmaterial); clabel.position.z=.09; coin1.add(clabel);
    coin1.position.set(-1.83,-1.54,.45); coin1.rotation.set(-.25,.54,-.28); main.add(coin1);
    const coin2 = coin1.clone(); coin2.scale.setScalar(.62); coin2.position.set(1.7,1.72,-.65); coin2.rotation.set(.4,-.5,.35); main.add(coin2);
    const etex=new THREE.TextureLoader().load(ethLogo); etex.colorSpace=THREE.SRGBColorSpace;
    const ematerial=cmaterial.clone();ematerial.map=etex;(coin2.children[2] as THREE.Mesh).material=ematerial;
    const liquidUniform={value:0};
    const liquidMaterial=new THREE.MeshPhysicalMaterial({color:'#c7ac7e',metalness:.3,roughness:.06,transmission:.72,thickness:1.4,ior:1.44,clearcoat:1,envMapIntensity:1.8,transparent:true,opacity:.6});
    liquidMaterial.onBeforeCompile=shader=>{shader.uniforms.uLiquidTime=liquidUniform;shader.vertexShader='uniform float uLiquidTime;\n'+shader.vertexShader;shader.vertexShader=shader.vertexShader.replace('#include <begin_vertex>','#include <begin_vertex>\nfloat swell=sin(position.x*2.8+uLiquidTime)*cos(position.y*2.2-uLiquidTime*.7)*sin(position.z*2.4+uLiquidTime*.5); transformed += normal*swell*.18;');};
    const liquidOrb=new THREE.Mesh(new THREE.IcosahedronGeometry(1.7,4),liquidMaterial);liquidOrb.position.set(.6,.1,-1.7);liquidOrb.scale.set(1.18,1.3,.65);scene.add(liquidOrb);
    const key = new THREE.DirectionalLight('#fff5d7',5); key.position.set(-3,5,6); scene.add(key);
    const edge = new THREE.DirectionalLight('#d59532',3); edge.position.set(4,-2,3); scene.add(edge);
    const fill = new THREE.AmbientLight('#fff1d3',.6); scene.add(fill);
    let pointerX=0, pointerY=0, visible=true, raf=0;
    const motion = window.matchMedia('(prefers-reduced-motion: reduce)');
    const pointer = (e:PointerEvent) => { const bounds=el.getBoundingClientRect(); pointerX=(e.clientX-bounds.left)/bounds.width-.5; pointerY=(e.clientY-bounds.top)/bounds.height-.5; };
    const reset=()=>{pointerX=pointerY=0;};
    el.addEventListener('pointermove',pointer); el.addEventListener('pointerleave',reset);
    const resize = new ResizeObserver(()=> { const w=el.clientWidth,h=el.clientHeight; renderer.setSize(w,h); camera.aspect=w/h; camera.updateProjectionMatrix(); }); resize.observe(el);
    const observer=new IntersectionObserver(([entry])=>{visible=entry.isIntersecting;}); observer.observe(el);
    const render=(time:number)=>{raf=requestAnimationFrame(render); if(!visible || document.hidden || pauseRef.current)return; const t=time*.001;
      if(!motion.matches) {liquidUniform.value=t*.65;liquidOrb.rotation.z=Math.sin(t*.3)*.2;bar.position.y=.12+Math.sin(t*.85)*.21; bar.rotation.y=-.46+Math.sin(t*.45)*.13+pointerX*.24; bar.rotation.x=-.17+pointerY*.1;coin1.rotation.y=.54+Math.sin(t*.7)*.24; coin1.position.y=-1.54+Math.sin(t+1)*.25;coin2.position.y=1.72+Math.sin(t*.8)*.23;coin2.rotation.z=.35+Math.sin(t*.4)*.2;}
      renderer.render(scene,camera);
    }; raf=requestAnimationFrame(render);
    return()=> {cancelAnimationFrame(raf);resize.disconnect();observer.disconnect();el.removeEventListener('pointermove',pointer);el.removeEventListener('pointerleave',reset); const geometries=new Set<THREE.BufferGeometry>();const materials=new Set<THREE.Material>();scene.traverse(obj=>{if(obj instanceof THREE.Mesh){geometries.add(obj.geometry);(Array.isArray(obj.material)?obj.material:[obj.material]).forEach(m=>materials.add(m));}});geometries.forEach(g=>g.dispose());materials.forEach(m=>m.dispose());texture.dispose();ctex.dispose();etex.dispose();environment.dispose();room.dispose();pmrem.dispose();renderer.dispose();renderer.domElement.remove();};
  },[]);
  return <div className="gold-scene" ref={host} aria-label="Animated three-dimensional gold bar and coins" role="img">{failed && <div className="fallback-ingot"><span>GOLDSWAP</span><b>Au</b><span>FINE GOLD<br/>999.9</span></div>}</div>;
}
